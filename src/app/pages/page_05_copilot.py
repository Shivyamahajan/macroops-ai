"""Page 5: AI Operations Copilot — MacroOps AI"""
import streamlit as st
import sys
sys.path.append('.')


@st.cache_resource
def get_sop():
    try:
        from src.ai.rag_pipeline import SOPAssistant
        return SOPAssistant()
    except Exception:
        return None


def render(store_id: str = None):
    st.markdown('<div class="main-header">🤖 AI Operations Copilot</div>',
                unsafe_allow_html=True)
    st.markdown('<div class="sub-header">Ask operational questions in plain '
                'language. Figures are computed from the data, never '
                'generated by the language model.</div>',
                unsafe_allow_html=True)

    if 'copilot' not in st.session_state:
        from src.ai.copilot import OperationsCopilot
        st.session_state.copilot = OperationsCopilot(get_sop())
        st.session_state.cop_msgs = []
    if get_sop() is None:
        st.warning("SOP knowledge base not found; procedure questions are "
                   "disabled. Run `python src/ai/build_knowledge_base.py`.")

    with st.sidebar:
        st.markdown("### Try asking")
        examples = ["What is the SLA breach rate?",
                    "Which 5 stores have the worst SLA performance?",
                    "Who are the 5 slowest pickers?",
                    "Which SKUs are out of stock?",
                    "What is the average rider assignment delay?",
                    "Which stores have the lowest inventory accuracy?",
                    "What should I do about slow picking?"]
        for ex in examples:
            if st.button(ex, key=f"ex_{ex[:18]}"):
                st.session_state.pending = ex
        if st.button("🗑️ Clear chat"):
            st.session_state.cop_msgs = []
            st.rerun()

    for m in st.session_state.cop_msgs:
        with st.chat_message(m['role']):
            st.markdown(m['content'])
            if m.get('table') is not None:
                st.dataframe(m['table'], use_container_width=True)
            if m.get('caption'):
                st.caption(m['caption'])

    q = st.chat_input("Ask about orders, pickers, inventory, riders, SOPs...")
    q = st.session_state.pop('pending', None) or q
    if not q:
        return

    st.session_state.cop_msgs.append({'role': 'user', 'content': q})
    with st.chat_message('user'):
        st.markdown(q)
    with st.chat_message('assistant'):
        with st.spinner("Working..."):
            r = st.session_state.copilot.ask(q)
        st.markdown(r['answer'])
        if r['table'] is not None:
            st.dataframe(r['table'], use_container_width=True)
        cap = (f"Source: {', '.join(dict.fromkeys(r['sources']))} · "
               f"{r['latency_ms']/1000:.1f}s" if r['sources']
               else f"{r['latency_ms']/1000:.1f}s")
        st.caption(cap)
    st.session_state.cop_msgs.append(
        {'role': 'assistant', 'content': r['answer'],
         'table': r['table'], 'caption': cap})
render()